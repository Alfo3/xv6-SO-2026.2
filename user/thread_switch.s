.globl thread_switch
thread_switch:
    # a0: puntero al struct thread_context de la hebra actual (old)
    # a1: puntero al struct thread_context de la hebra siguiente (new)

    # 1. Guardar los registros callee-saved de la hebra actual en *a0
    sd ra, 0(a0)
    sd sp, 8(a0)
    sd s0, 16(a0)
    sd s1, 24(a0)
    sd s2, 32(a0)
    sd s3, 40(a0)
    sd s4, 48(a0)
    sd s5, 56(a0)
    sd s6, 64(a0)
    sd s7, 72(a0)
    sd s8, 80(a0)
    sd s9, 88(a0)
    sd s10, 96(a0)
    sd s11, 104(a0)

    # 2. Cargar los registros callee-saved de la nueva hebra desde *a1
    ld ra, 0(a1)
    ld sp, 8(a1)
    ld s0, 16(a1)
    ld s1, 24(a1)
    ld s2, 32(a1)
    ld s3, 40(a1)
    ld s4, 48(a1)
    ld s5, 56(a1)
    ld s6, 64(a1)
    ld s7, 72(a1)
    ld s8, 80(a1)
    ld s9, 88(a1)
    ld s10, 96(a1)
    ld s11, 104(a1)

    # 3. Retornar: salta a la dirección cargada en 'ra' (de la nueva hebra)
    ret